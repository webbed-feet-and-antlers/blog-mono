"""Report collection + baselines.

Suites call `record(...)` for every (case, metric) pair. At session end the
records are aggregated per suite into evals/reports/<run>/, EVALS.md is
regenerated from the latest run, and any committed baselines are diffed.

    uv run python -m evals.report            # re-render + diff from CLI
    uv run python -m evals.report --promote  # copy latest run → baselines/
"""

from __future__ import annotations

import json
import shutil
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from evals.config import BASELINES_DIR, REPORTS_DIR

RECORDS: list[dict] = []


def record(
    suite: str,
    metric: str,
    *,
    case: str,
    score: float,
    threshold: float | None = None,
    success: bool | None = None,
    reason: str = "",
) -> None:
    """Record one (case, metric) observation. Cheap; called per case."""
    RECORDS.append(
        {
            "suite": suite,
            "metric": metric,
            "case": str(case),
            "score": round(float(score), 4),
            "threshold": threshold,
            "success": success,
            "reason": reason[:500],
        }
    )


def _aggregate(records: list[dict]) -> dict:
    """records for ONE suite → {metric: {mean, n, threshold, failures[]}}."""
    by_metric: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        by_metric[r["metric"]].append(r)
    out = {}
    for metric, rows in sorted(by_metric.items()):
        scores = [r["score"] for r in rows]
        failures = [
            {"case": r["case"], "score": r["score"], "reason": r["reason"]}
            for r in rows
            if r["success"] is False
        ]
        thresholds = [r["threshold"] for r in rows if r["threshold"] is not None]
        out[metric] = {
            "mean": round(sum(scores) / len(scores), 4),
            "min": min(scores),
            "n": len(scores),
            "threshold": thresholds[0] if thresholds else None,
            "failures": failures[:20],  # cap — the JSON stays readable
        }
    return out


def flush_reports() -> Path | None:
    """Write the run's reports + regenerate EVALS.md. Called at session end."""
    if not RECORDS:
        return None
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_dir = REPORTS_DIR / ts
    run_dir.mkdir(parents=True, exist_ok=True)

    by_suite: dict[str, list[dict]] = defaultdict(list)
    for r in RECORDS:
        by_suite[r["suite"]].append(r)

    summary = {}
    for suite, rows in sorted(by_suite.items()):
        agg = _aggregate(rows)
        (run_dir / f"{suite}.json").write_text(
            json.dumps(
                {"suite": suite, "run": ts, "metrics": agg}, indent=2
            )
        )
        summary[suite] = agg
    (run_dir / "summary.json").write_text(
        json.dumps({"run": ts, "suites": summary}, indent=2)
    )
    latest = REPORTS_DIR / "latest"
    if latest.exists():
        shutil.rmtree(latest)
    shutil.copytree(run_dir, latest)

    _write_markdown(run_dir)
    RECORDS.clear()
    return run_dir


def _baseline_for(suite: str) -> dict | None:
    path = BASELINES_DIR / f"{suite}.json"
    if not path.exists():
        return None
    return json.loads(path.read_text())


def _write_markdown(run_dir: Path) -> None:
    """Regenerate EVALS.md: latest-run metrics with deltas vs baselines."""
    lines = [
        "# Eval results",
        "",
        "Generated by `task study-app:evals` — see `evals/README.md` for how to",
        "run suites, and `reports/baselines/` for the committed reference run.",
        "",
    ]
    for suite_json in sorted(run_dir.glob("*.json")):
        if suite_json.name == "summary.json":
            continue
        data = json.loads(suite_json.read_text())
        suite = data["suite"]
        baseline = _baseline_for(suite)
        lines += [f"## {suite}", "", "| metric | mean | n | baseline | Δ |", "|---|---|---|---|---|"]
        for metric, agg in data["metrics"].items():
            base_cell, delta_cell = "—", "—"
            if baseline and metric in baseline.get("metrics", {}):
                base = baseline["metrics"][metric]["mean"]
                base_cell = f"{base:.3f}"
                delta_cell = f"{agg['mean'] - base:+.3f}"
            lines.append(
                f"| {metric} | {agg['mean']:.3f} | {agg['n']} | {base_cell} | {delta_cell} |"
            )
        lines.append("")
    (REPORTS_DIR.parent / "EVALS.md").write_text("\n".join(lines))


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Eval report tooling")
    parser.add_argument(
        "--promote",
        action="store_true",
        help="copy reports/latest/*.json → reports/baselines/ (commit these)",
    )
    args = parser.parse_args()
    if args.promote:
        latest = REPORTS_DIR / "latest"
        if not latest.exists():
            raise SystemExit("no reports/latest/ — run the evals first")
        BASELINES_DIR.mkdir(parents=True, exist_ok=True)
        for f in latest.glob("*.json"):
            if f.name != "summary.json":
                shutil.copy(f, BASELINES_DIR / f.name)
        print(f"baselines updated from {latest}")
    else:
        latest = REPORTS_DIR / "latest"
        if not latest.exists():
            raise SystemExit("no reports/latest/ — run the evals first")
        _write_markdown(latest)
        print(f"EVALS.md regenerated from {latest}")


if __name__ == "__main__":
    main()
