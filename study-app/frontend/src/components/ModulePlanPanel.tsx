import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useNavigate } from "@tanstack/react-router";
import {
  CalendarDays,
  Sparkles,
  RefreshCw,
  Zap,
  CircleHelp,
  Layers,
  FileText,
  PenLine,
  BrainCircuit,
} from "lucide-react";
import * as api from "../api/client";
