// Substack — has NO public posting API (confirmed July 2026 across Buffer,
// Postiz, dlvr.it, Narrareach — none can post to Substack). Also no canonical
// URL support, so full-text cross-posts are an SEO risk.
//
// Instead of posting, this adapter builds a paste-ready teaser (title + the
// socialPost blurb + a canonical link) and writes it to the output directory,
// which the workflow uploads as a downloadable artifact. You paste it manually.
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
// scripts/lib/platforms -> site/.syndication-output
const OUT_DIR = join(__dirname, '..', '..', '..', '.syndication-output');

export const name = 'substack';

export function available() {
  return true; // always — it's a manual step, needs no credentials
}

/**
 * @param {object} opts
 * @param {string} opts.title
 * @param {string} opts.socialPost     - the blurb to use as the teaser body
 * @param {string} opts.canonicalUrl
 * @param {string} opts.slug           - essay slug (for the filename)
 * @returns {Promise<{id: string, url: string, teaser: string}>}
 */
export async function publish({ title, socialPost, canonicalUrl, slug }) {
  const teaser = [
    `# ${title}`,
    '',
    socialPost || '(No socialPost blurb defined — write one in the essay frontmatter.)',
    '',
    `Read the full essay with interactive components on our site: ${canonicalUrl}`,
    '',
    '---',
    'Generated by scripts/syndicate.mjs — paste manually into Substack.',
    'Substack has no posting API and no canonical-URL support, so we post a',
    'teaser + link rather than the full body (SEO-safe).',
  ].join('\n');

  await mkdir(OUT_DIR, { recursive: true });
  const file = join(OUT_DIR, `substack-${slug}.md`);
  await writeFile(file, teaser, 'utf8');

  return { id: 'manual', url: '(manual paste)', teaser };
}

export function publicUrl() {
  return undefined; // unknown until manually posted
}
